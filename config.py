"""
=============================================================================
  配置文件 —— 整个项目的超参数、路径和全局设置
=============================================================================

本项目解决的核心问题：
  给定沪深 300 成分股过去 60 个交易日的量价数据，预测未来一周（T+1 到 T+5）
  收益最高的不超过 5 只股票，并分配权重。

模型思路（注意力机制 + 排序学习）：
  1. 用时序编码器（GRU）提取每只股票的时序特征
  2. 用截面自注意力（Cross-Sectional Self-Attention）让股票之间互相"看"
     学习它们之间的相关结构，实现隐式的分散化
  3. 用排序损失（LambdaRank）训练，直接优化股票的相对排序而非精确收益率
  4. 选股时用 embedding 的余弦相似度做贪心多样化，避免选中高度相关的股票

相关论文参考：
  - LambdaRank: Burges et al., "Learning to Rank using Gradient Descent", ICML 2005
  - Attention is All You Need: Vaswani et al., NeurIPS 2017
  - 股票排序预测: "Transformer-based Ranking for Stock Selection"
=============================================================================
"""

